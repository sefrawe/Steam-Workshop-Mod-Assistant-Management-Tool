    # ---------- 基建 ----------

    @staticmethod
    def _hline() -> QFrame:
        """主题安全的水细分隔线：QFrame 线条取色自系统调色板，
        深色/亮色主题都不用管（零硬编码颜色）。"""
        line = QFrame()
        line.setFrameShape(QFrame.Shape.HLine)
        line.setFrameShadow(QFrame.Shadow.Sunken)
        return line

    def _section(self, title: str, lines: list[str]) -> None:
        """一节 = 节头 + 若干行，每行独立 QLabel。
        整节挤一个 QLabel 的老写法，任何一行折行都会影响整块排版；
        拆行后各管各的。节头上边距 12px = 节间留白（行距只有 4，
        靠这里拉开层级）。空字符串行会塌成 0 高，所以空行一律传
        一个空格 " "。"""
        head = QLabel(title, self)
        head.setStyleSheet(f"font-size: {font_px(15)}px; font-weight: 600;")
        head.setContentsMargins(0, 12, 0, 2)
        self._body.addWidget(head)
        for text in lines:
            lab = QLabel(text, self)
            lab.setWordWrap(True)  # 会变高折行的标签必须开自动换行（老坑⑨）
            lab.setTextInteractionFlags(
                Qt.TextInteractionFlag.TextSelectableByMouse)  # 可选中复制
            self._body.addWidget(lab)
